#!/usr/bin/env python3
"""Build the x86 shared library used by the host whole-model numerical check.

The lowered graph calls the generated model adapters (vit_triton_adapters.c),
which in turn call one typed entry per kernel case.  On the host those case
entries are replaced by stubs that dispatch into tools/model_host_oracle.py,
which evaluates the per-case independent reference (oracles.py).  This lets
check_w8a8_graph_host.py exercise the real rewritten graph, parameter packing
and workspace ABI without an FPGA.
"""

from __future__ import annotations

import argparse
import json
import re
import shutil
import subprocess
import sys
from pathlib import Path

V = Path(__file__).resolve().parents[1]
REPO = V.parents[2]
BUDDY = REPO / "buddy-mlir"
RUNTIME = BUDDY / "runtime" / "boscame"

KERNEL_EXTERN = re.compile(
    r"^extern void (_mlir_ciface_kernel_[A-Za-z0-9_]+)\(([^)]*)\);", re.MULTILINE
)


def host_compiler():
    for candidate in (shutil.which("gcc"), shutil.which("cc"), shutil.which("clang")):
        if candidate:
            return candidate
    raise RuntimeError("no host C compiler found (gcc/cc/clang)")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--replacement", type=Path, default=V / "build/replacement-w8a8"
    )
    parser.add_argument("--output", type=Path, default=V / "build/model-host")
    parser.add_argument("--compiler", default=None)
    args = parser.parse_args()
    args.output.mkdir(parents=True, exist_ok=True)

    adapters = args.replacement / "vit_triton_adapters.c"
    source = adapters.read_text()
    externs = KERNEL_EXTERN.findall(source)
    if not externs:
        raise RuntimeError("no _mlir_ciface_kernel_ externs found in adapters")
    seen = {}
    for symbol, params in externs:
        seen.setdefault(symbol, params)
    cases = []
    for index, symbol in enumerate(sorted(seen)):
        case = symbol[len("_mlir_ciface_kernel_") :]
        params = seen[symbol].strip()
        ranks = [int(rank) for rank in re.findall(r"MemRef(\d+)", params)]
        cases.append(
            {
                "index": index,
                "case": case,
                "symbol": symbol,
                "ranks": ranks,
                "params": params,
            }
        )
    if len(cases) != 28:
        raise RuntimeError("expected 28 kernel cases, found %d" % len(cases))

    lines = [
        "/* Generated by tools/build_model_host.py. Do not edit. */",
        "#include <stddef.h>",
        "#include <stdint.h>",
        '#include "support.h"',
        "",
        "typedef void (*host_kernel_dispatch_fn)(int, void *const *, int);",
        "static host_kernel_dispatch_fn host_kernel_dispatch;",
        "void host_model_bind(host_kernel_dispatch_fn fn) { host_kernel_dispatch = fn; }",
        "",
    ]
    for record in cases:
        typed_params = ", ".join(
            "MemRef%d *a%d" % (rank, index)
            for index, rank in enumerate(record["ranks"])
        )
        args_list = ", ".join(
            "(void *)%s" % name
            for name in ["a%d" % i for i in range(len(record["ranks"]))]
        )
        lines.append("void %s(%s) {" % (record["symbol"], typed_params))
        lines.append("  void *args[%d] = {%s};" % (len(record["ranks"]), args_list))
        lines.append(
            "  host_kernel_dispatch(%d, args, %d);"
            % (record["index"], len(record["ranks"]))
        )
        lines.append("}")
        lines.append("")
    kernels = args.output / "host_kernels.c"
    kernels.write_text("\n".join(lines))
    (args.output / "host-cases.json").write_text(json.dumps(cases, indent=2) + "\n")

    compiler = args.compiler or host_compiler()
    library = args.output / "libvit_model_host.so"
    command = [
        compiler,
        "-O2",
        "-fPIC",
        "-shared",
        "-Wno-implicit-function-declaration",
        "-I",
        str(V),
        "-I",
        str(V / "tools"),
        "-I",
        str(RUNTIME),
        "-I",
        str(RUNTIME / "nr"),
        "-I",
        str(RUNTIME / "runtime"),
        str(adapters),
        str(kernels),
        str(V / "tools" / "model_host_support.c"),
        "-o",
        str(library),
    ]
    process = subprocess.run(
        command, text=True, stdout=subprocess.PIPE, stderr=subprocess.STDOUT
    )
    if process.returncode:
        raise RuntimeError("host library build failed:\n" + process.stdout)
    undefined = (
        subprocess.run(
            ["nm", "-D", "-u", str(library)],
            text=True,
            stdout=subprocess.PIPE,
            stderr=subprocess.STDOUT,
        )
        .stdout.strip()
        .splitlines()
    )
    print(
        json.dumps(
            {
                "library": str(library),
                "bytes": library.stat().st_size,
                "kernel_cases": len(cases),
                "undefined": [line.split()[-1] for line in undefined],
            },
            indent=2,
        )
    )


if __name__ == "__main__":
    sys.exit(main())
