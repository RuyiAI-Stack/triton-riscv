#!/usr/bin/env python3
"""Run E5, download complete outputs, and compare frozen emitted-code bytes."""

import argparse
import json
import os
import re
import shutil
import subprocess
import time
import uuid
from pathlib import Path

from verify_model_emitted import freeze_reference, save, sha, validate

ROOT = Path(__file__).resolve().parents[1]
REPO = ROOT.parents[2]
SIBLING_CLIENT = REPO.parent / "fpga-scheduler/.venv/bin/fpga-scheduler"


def cli(base, arguments, directory, label):
    result = subprocess.run(
        base + arguments, capture_output=True, text=True, check=False
    )
    (directory / (label + ".stdout")).write_text(result.stdout)
    (directory / (label + ".stderr")).write_text(result.stderr)
    if result.returncode:
        raise RuntimeError(f"scheduler {label} failed: " + result.stderr[-1200:])
    return json.loads(result.stdout)


def review(run, reference, destination):
    """Revalidate archived evidence without changing a single original file."""
    destination.mkdir(parents=True, exist_ok=False)
    freeze_reference(reference, run, destination / "emitted-reference")
    report = validate(run, destination / "emitted-reference", destination)
    for source in (Path(__file__), ROOT / "tools/verify_model_emitted.py"):
        shutil.copyfile(source, destination / source.name)
    save(
        destination / "review.json",
        {
            "run": str(run),
            "reference": str(reference),
            "task_id": report["task_id"],
            "status": report["status"],
            "validation_sha256": sha(destination / "local-validation.json"),
        },
    )
    print(report["status"], report["task_id"], "review", destination, flush=True)
    return report["status"] != "MODEL_NUMERICAL_PASS"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--client",
        default=os.environ.get(
            "FPGA_SCHEDULER_CLIENT",
            str(SIBLING_CLIENT) if SIBLING_CLIENT.is_file() else "fpga-scheduler",
        ),
    )
    parser.add_argument(
        "--endpoint",
        default=os.environ.get("FPGA_SCHEDULER_URL", "http://127.0.0.1:18762"),
    )
    parser.add_argument(
        "--token-file",
        type=Path,
        default=os.environ.get(
            "FPGA_SCHEDULER_TOKEN_FILE", str(REPO / ".agent/secrets/fpga112.token")
        ),
    )
    parser.add_argument("--build", type=Path, default=ROOT / "build/model-board")
    parser.add_argument(
        "--output",
        type=Path,
        help="new execution evidence directory; existing run directory for --validate-only",
    )
    parser.add_argument("--timeout", type=int, default=1800)
    parser.add_argument(
        "--validate-only",
        action="store_true",
        help="local recheck only; no scheduler calls",
    )
    parser.add_argument(
        "--review-output",
        type=Path,
        help="new directory for --validate-only results; defaults to a fresh sibling of the run",
    )
    parser.add_argument(
        "--emitted-reference",
        type=Path,
        default=ROOT / "build/model-host",
        help="required existing build_model_host.py execution; never generated by this runner",
    )
    args = parser.parse_args()
    if args.validate_only and args.output is None:
        parser.error(
            "--validate-only requires --output PATH to an existing evidence directory"
        )
    if args.review_output and not args.validate_only:
        parser.error("--review-output is only for --validate-only")
    if args.output is None:
        args.output = (
            ROOT
            / "build/model-board-runs"
            / time.strftime("run-%Y%m%d-%H%M%S", time.gmtime())
        )
    args.build = args.build.resolve()
    args.output = args.output.resolve()
    args.emitted_reference = args.emitted_reference.resolve()
    if not (args.emitted_reference / "manifest.json").is_file():
        raise ValueError(
            "missing emitted reference; run make model-host first: "
            + str(args.emitted_reference)
        )
    if args.validate_only:
        destination = (
            args.review_output.resolve()
            if args.review_output
            else args.output.with_name(
                args.output.name + "-review-" + uuid.uuid4().hex[:12]
            )
        )
        return review(args.output, args.emitted_reference, destination)

    result_path = args.output / "result.json"
    frozen_reference = args.output / "emitted-reference"
    if result_path.exists():
        record = json.loads(result_path.read_text())
        # Recovery must use the exact pre-submission frozen oracle. Never regenerate it.
        receipt = json.loads((frozen_reference / "frozen.json").read_text())
        for name, expected in receipt["files"].items():
            if sha(frozen_reference / name) != expected:
                raise ValueError("frozen emitted reference changed: " + name)
    else:
        if args.output.exists() and any(args.output.iterdir()):
            raise ValueError("new execution requires an empty --output directory")
        args.output.mkdir(parents=True, exist_ok=True)
        build = json.loads((args.build / "build.json").read_text())
        if sha(args.build / "e5_model.bin") != build["image_sha256"]:
            raise ValueError("stale model binary")
        audit = json.loads((args.build / "elf-audit.json").read_text())
        if audit["status"] != "PASS" or audit["elf_sha256"] != sha(
            args.build / "e5_model.elf"
        ):
            raise ValueError("stale ELF audit")
        names = [
            "e5_model.bin",
            "e5_model.elf",
            "elf-audit.json",
            "build.json",
            "input_reference.json",
            "params.json",
            "inputs.bin",
            "operator_trace.json",
        ]
        for name in names:
            shutil.copyfile(args.build / name, args.output / name)
        for relative, expected in build["sources"].items():
            if sha(REPO / relative) != expected:
                raise ValueError("source changed after build " + relative)
            target = args.output / "sources" / relative
            target.parent.mkdir(parents=True, exist_ok=True)
            shutil.copyfile(REPO / relative, target)
        # Fail closed before scheduler requests if the required execution is absent or stale.
        freeze_reference(args.emitted_reference, args.output, frozen_reference)
        record = {
            "status": "PREPARED",
            "server": "fpga112",
            "task_id": uuid.uuid4().hex,
            "image_sha256": build["image_sha256"],
            "image_bytes": build["image_bytes"],
            "timeout": args.timeout,
            "frozen_files": {name: sha(args.output / name) for name in names},
            "emitted_reference_receipt_sha256": sha(frozen_reference / "frozen.json"),
        }
        for source in (Path(__file__), ROOT / "tools/verify_model_emitted.py"):
            shutil.copyfile(source, args.output / source.name)
        save(result_path, record)

    base = [
        args.client,
        "--endpoint",
        args.endpoint,
        "--token-file",
        str(args.token_file.expanduser().resolve()),
        "--json",
    ]
    if record["status"] != "PREPARED":
        task = cli(base, ["job", record["task_id"]], args.output, "recovery-query")
        if task["state"] not in ("completed", "failed", "cancelled"):
            raise RuntimeError(
                "original task is nonterminal; no resubmission: " + record["task_id"]
            )
        save(args.output / "task.json", task)
    else:
        health = cli(base, ["health"], args.output, "health-before")
        devices = cli(base, ["devices"], args.output, "devices-before")
        if (
            health.get("stopping")
            or health.get("scheduler_error")
            or not health.get("dispatcher_alive")
        ):
            raise RuntimeError("scheduler is unhealthy; no submission")
        if not any(
            d.get("available") and d.get("state") == "READY" for d in devices["devices"]
        ):
            raise RuntimeError("no READY FPGA; no submission")
        command = base + [
            "run",
            str(args.output / "e5_model.bin"),
            "--id",
            record["task_id"],
            "--name",
            "e5-small-v2/full-model-real-checkpoint",
            "--timeout",
            str(record["timeout"]),
            "--queue-timeout",
            "3600",
        ]
        record.update(status="SUBMITTING", command=command)
        save(result_path, record)
        print("RUN", record["task_id"], "bytes", record["image_bytes"], flush=True)
        # The foreground client owns and renews its lease through completion.
        with (
            (args.output / "client.stdout").open("w") as out,
            (args.output / "client.stderr").open("w") as err,
        ):
            process = subprocess.Popen(command, stdout=out, stderr=err)
            started = time.monotonic()
            last = -60
            while process.poll() is None:
                elapsed = time.monotonic() - started
                if elapsed - last >= 60:
                    print(
                        "MODEL_CLIENT_ALIVE",
                        record["task_id"],
                        "elapsed_seconds",
                        int(elapsed),
                        flush=True,
                    )
                    last = elapsed
                time.sleep(2)
        record["client_returncode"] = process.returncode
        save(result_path, record)
        try:
            task = json.loads((args.output / "client.stdout").read_text())
        except json.JSONDecodeError:
            record["status"] = "CONNECTION_OR_CLIENT_ERROR"
            save(result_path, record)
            task = cli(
                base, ["job", record["task_id"]], args.output, "same-id-recovery"
            )
            save(args.output / "task.json", task)
            raise RuntimeError(
                "client failed; original task queried, no resubmission"
            ) from None
        save(args.output / "task.json", task)
    result = task.get("result") or {}
    details = result.get("details") or {}
    record.update(
        state=task["state"],
        fpga=task.get("fpga"),
        execution_status=result.get("execution_status"),
        app_exit_code=result.get("app_exit_code"),
        exit_code=result.get("exit_code"),
        details=details,
        scheduler_seconds=result.get("seconds"),
    )
    uart = result.get("uart_output") or result.get("output") or ""
    (args.output / "uart.log").write_text(uart)
    record["model_cycles"] = [
        int(c, 16) for c in re.findall(r"model_cycles=0x([0-9a-fA-F]+)", uart)
    ]
    save(result_path, record)
    if (
        task["id"] != record["task_id"]
        or task["state"] != "completed"
        or result.get("execution_status") != "exited"
        or result.get("exit_code") != 0
        or result.get("app_exit_code") != 0
        or details.get("ddr_readback_matches") is not True
        or details.get("image_sha256") != record["image_sha256"]
        or details.get("artifact_error")
        or not re.search(r"kernel_calls=1649 checkpoints=13", uart)
    ):
        record["status"] = "APPLICATION_OR_PLATFORM_FAIL"
        save(result_path, record)
        print(record["status"], record["task_id"], uart[-4000:], flush=True)
        return 1
    artifacts = cli(
        base, ["artifacts", record["task_id"]], args.output, "artifacts-list"
    )
    if artifacts["id"] != record["task_id"]:
        raise ValueError("artifact list task mismatch")
    target = args.output / "artifacts"
    target.mkdir(exist_ok=True)
    save(target / "manifest.json", artifacts)
    for item in artifacts["artifacts"]:
        path = target / (item["name"] + ".bin")
        cli(
            base,
            ["download", record["task_id"], item["name"], str(path)],
            args.output,
            "download-" + item["name"],
        )
        if path.stat().st_size != item["nbytes"] or sha(path) != item["sha256"]:
            raise ValueError("download SHA mismatch")
    record.update(artifacts=artifacts["artifacts"], status="DOWNLOADED")
    save(result_path, record)
    report = validate(args.output, frozen_reference, args.output)
    record["status"] = (
        "PASS" if report["status"] == "MODEL_NUMERICAL_PASS" else "NUMERICAL_FAIL"
    )
    record["local_validation_sha256"] = sha(args.output / "local-validation.json")
    save(result_path, record)
    print(
        record["status"],
        record["task_id"],
        "fpga",
        record["fpga"],
        "model_cycles",
        record["model_cycles"],
        flush=True,
    )
    return record["status"] != "PASS"


if __name__ == "__main__":
    raise SystemExit(main())
