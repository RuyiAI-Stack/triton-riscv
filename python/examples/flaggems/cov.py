_DOT_PRECISION = tl.constexpr("ieee" if _NEEDS_IEEE_DOT else "ieee")


@triton.jit
def _cov_mean_kernel(
    x_ptr,
    w_ptr,
    mean_ptr,
    n_rows,
    n_cols,
    w_sum,
    stride_xn,
    stride_xm,
    HAS_W: tl.constexpr,
    BLOCK_M: tl.constexpr,
):
    row = tl.program_id(0)
    acc = tl.zeros([BLOCK_M], dtype=tl.float32)
    for m_start in range(0, n_cols, BLOCK_M):
        offs = m_start + tl.arange(0, BLOCK_M)
        mask = offs < n_cols
        x = tl.load(x_ptr + row * stride_xn + offs * stride_xm, mask=mask, other=0.0)
        x = x.to(tl.float32)
        if HAS_W:
            w = tl.load(w_ptr + offs, mask=mask, other=0.0).to(tl.float32)
            x = x * w
        acc += x
    mean = tl.sum(acc) / w_sum
    tl.store(mean_ptr + row, mean)


