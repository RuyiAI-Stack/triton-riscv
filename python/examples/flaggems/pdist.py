def pdist(x, p=2.0):
    """Compute p-norm distance between every pair of row vectors in the input.

    Args:
        x: Input tensor of shape (N, M)
        p: p value for the p-norm distance to calculate

    Returns:
        Tensor of shape (N*(N-1)//2,) containing pairwise distances
    """
    logger.debug("GEMS PDIST")
    assert x.ndim == 2, "pdist only supports 2D input"
    if x.dtype != torch.float32:
        raise RuntimeError(
            f"pdist Triton kernel supports torch.float32, but got {x.dtype}"
        )
    N = x.shape[0]
    M = x.shape[1]
    if N < 2:
        raise ValueError("pdist requires at least 2 rows")
    x = x.contiguous()
    num_pairs = N * (N - 1) // 2
    out = torch.empty(num_pairs, dtype=x.dtype, device=x.device)
    BLOCK_M = min(triton.next_power_of_2(M), 1024)
    if p == 2.0:
        _pdist_forward_p2_kernel[num_pairs,](
            x, out, N, M, x.stride(0), out.stride(0), BLOCK_M=BLOCK_M
        )
    elif p == 1.0:
        _pdist_forward_p1_kernel[num_pairs,](
            x, out, N, M, x.stride(0), out.stride(0), BLOCK_M=BLOCK_M
        )
    elif math.isinf(p):
        _pdist_forward_inf_kernel[num_pairs,](
            x, out, N, M, x.stride(0), out.stride(0), BLOCK_M=BLOCK_M
        )
    else:
        _pdist_forward_general_kernel[num_pairs,](
            x, out, N, M, p, x.stride(0), out.stride(0), BLOCK_M=BLOCK_M
        )
    return out
