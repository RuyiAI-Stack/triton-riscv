def _inverse_std(VAR, OUT, N, EPS: tl.constexpr, BLOCK: tl.constexpr):
    i = tl.program_id(0) * BLOCK + tl.arange(0, BLOCK)
    var = tl.load(VAR + i, i < N, other=0).to(tl.float32)
    tl.store(OUT + i, tl.rsqrt(var + EPS), i < N)


