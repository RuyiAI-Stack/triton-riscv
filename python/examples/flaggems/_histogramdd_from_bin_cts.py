def histogramdd_density_kernel(
    hist_ptr,
    out_ptr,
    scale_ptr,
    num_bins,
    ACC_DTYPE: tl.constexpr,
    BLOCK_SIZE: tl.constexpr,
):
    """Normalize counts into a density: density[i] = count[i] / (total * volume)."""
    pid = tl.program_id(0)
    offset = pid * BLOCK_SIZE + tl.arange(0, BLOCK_SIZE)
