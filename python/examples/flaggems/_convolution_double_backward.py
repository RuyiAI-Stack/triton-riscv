    pad_h, pad_w = _pair(padding)
    dil_h, dil_w = _pair(dilation)
    gO_h, gO_w = (gO.shape[2], gO.shape[3])
    self_h, self_w = (self.shape[2], self.shape[3])
    kH, kW = (weight.shape[2], weight.shape[3])
    grad_ggO = None
    grad_self = None
    grad_weight = None
    parts = []
    if ggI is not None:
        if not transposed:
            parts.append(
                conv2d(
                    ggI,
                    weight,
                    stride=stride,
                    padding=padding,
                    dilation=dilation,
                    groups=groups,
                )
            )
        else:
            parts.append(
                conv_transpose2d(
                    ggI,
                    weight,
                    stride=stride,
                    padding=padding,
                    output_padding=output_padding,
                    groups=groups,
                    dilation=dilation,
                )
            )
    if ggW is not None:
        if not transposed:
            parts.append(
                conv2d(
                    self,
                    ggW,
                    stride=stride,
                    padding=padding,
                    dilation=dilation,
                    groups=groups,
                )
            )
        else:
            parts.append(
                conv_transpose2d(
                    self,
                    ggW,
                    stride=stride,
                    padding=padding,
                    output_padding=output_padding,
                    groups=groups,
                    dilation=dilation,
                )
            )
    if ggb is not None:
        bias_part = ggb.view(1, -1, 1, 1).expand(1, ggb.shape[0], gO_h, gO_w)
        bias_part = bias_part.expand(gO.shape[0], -1, -1, -1)
        parts.append(bias_part)
    if parts:
        grad_ggO = parts[0]
        for p in parts[1:]:
            grad_ggO = add(grad_ggO, p)
    if ggW is not None:
        if not transposed:
            opad_self_h = self_h - (
                (gO_h - 1) * stride_h - 2 * pad_h + dil_h * (kH - 1) + 1
            )
            opad_self_w = self_w - (
                (gO_w - 1) * stride_w - 2 * pad_w + dil_w * (kW - 1) + 1
            )
            grad_self = conv_transpose2d(
                gO,
                ggW,
                stride=stride,
                padding=padding,
                output_padding=(opad_self_h, opad_self_w),
                groups=groups,
                dilation=dilation,
            )
        else:
            grad_self = conv2d(
                gO,
                ggW,
                stride=stride,
                padding=padding,
                dilation=dilation,
                groups=groups,
            )
    if ggI is not None:
        if not transposed:
            grad_weight = _grad_weight_correlation(
                ggI, gO, weight.shape, stride, padding, dilation, groups
            )
        else:
            grad_weight = _grad_weight_correlation(
                gO, ggI, weight.shape, stride, padding, dilation, groups
            )
    return (grad_ggO, grad_self, grad_weight)


