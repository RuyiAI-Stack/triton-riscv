def _put_impl(inp, index, source, accumulate=False):
    inp_numel = inp.numel()
    index_flat = _flatten(index)
    source_flat = _flatten(source)
    if index_flat.numel() == 0:
        return inp
    if inp_numel == 0:
        raise IndexError("put_(): Tried to put elements into an empty tensor")
    dtype = inp.dtype
    if dtype.is_complex:
        real_view = torch.view_as_real(inp)
        re, im = (real_view[..., 0], real_view[..., 1])
        src_real = torch.view_as_real(source_flat)
        _launch(re, index_flat, src_real[..., 0].contiguous(), accumulate)
        _launch(im, index_flat, src_real[..., 1].contiguous(), accumulate)
        return inp
    if accumulate and dtype in _NARROW_INT_DTYPES:
        staged = _stage_to_int32(inp)
        _launch(staged, index_flat, _stage_to_int32(source_flat), True)
        _stage_back(inp, staged)
        return inp
    if accumulate and dtype is torch.bool:
        staged = _stage_to_int32(inp, bool_normalize=True)
        _launch(
            staged, index_flat, _stage_to_int32(source_flat, bool_normalize=True), True
        )
        _stage_back(inp, staged, to_bool=True)
        return inp
    _launch(inp, index_flat, source_flat, accumulate)
    return inp


def put_(inp, index, source, accumulate=False):
    if index.numel() and bool(
        torch.any((index < -inp.numel()) | (index >= inp.numel()))
    ):
        raise IndexError("put index out of range")
    logger.debug("GEMS PUT_")
    if index.device != inp.device or source.device != inp.device:
        bad, name = (
            (index, "index") if index.device != inp.device else (source, "source")
        )
        raise RuntimeError(
            f"Expected all tensors to be on the same device, but got {name} is on {bad.device}, different from other tensors on {inp.device} (when checking argument in method wrapper_CUDA__put_)"
        )
    if index.dtype != torch.int64:
        raise RuntimeError(
            f"put_(): Expected a long tensor for index, but got {_SCALAR_TYPE_NAMES.get(index.dtype, str(index.dtype))}"
        )
    if source.dtype != inp.dtype:
        raise RuntimeError(
            f"put_(): self and source expected to have the same dtype, but got self.dtype = {_SCALAR_TYPE_NAMES.get(inp.dtype, str(inp.dtype))} and source.dtype = {_SCALAR_TYPE_NAMES.get(source.dtype, str(source.dtype))}"
        )
    if index.numel() != source.numel():
        raise IndexError(
            f"put_(): Expected source and index to have the same number of elements, but got source.numel() = {source.numel()}, index.numel() = {index.numel()}"
        )
    if inp.dtype == torch.complex32:
        raise NotImplementedError(
            f""""put_cuda" not implemented for '{_SCALAR_TYPE_NAMES.get(torch.complex32, "ComplexHalf")}'"""
        )
    _assert_no_internal_overlap(inp)
    index = _check_and_unalias(inp, index)
    source = _check_and_unalias(inp, source)
    return _put_impl(inp, index, source, accumulate)
